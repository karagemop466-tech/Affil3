#!/usr/bin/env node
/*
 * Special Link generator + validator.
 *
 * Why this exists as a separate command: the link format is the single place where this project can
 * quietly lose money and account standing at the same time (untagged = no attribution; a hand-pasted
 * link = no disclosure guarantee; a 9-character token pasted as an ASIN = a link to nothing).
 * So links are derived from the register, never typed. Run it whenever products.json changes:
 *
 *   node scripts/links.mjs            validate what is in the register
 *   node scripts/links.mjs --write    rewrite register/links.json from products.json
 *   node scripts/links.mjs --csv      emit the owner's one-link test sheet
 */
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const R = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), "utf8"));
const site = R("register/site.json");
const productsDoc = R("register/products.json");
const TRACK = site.tracking_id;
const ASIN = /^[A-Z0-9]{10}$/;
const write = process.argv.includes("--write");
const csv = process.argv.includes("--csv");

const errs = [];
const advisories = [];
const rows = [];

for (const p of productsDoc.products) {
  const asin = p.observed_redirect_target && p.observed_redirect_target.asin;
  const token = p.submitted_token;
  // a short token is a documented property of the supplied links (FLG-001), not a defect:
  // it is recorded, reported as an advisory, and never used as an identifier.
  if (token && !ASIN.test(token)) advisories.push(`${p.id}: submitted token "${token}" is ${token.length} chars, not 10 - a redirect handle, not an ASIN; used for provenance only`);
  if (p.intended_asin && !ASIN.test(p.intended_asin)) errs.push(`${p.id}: intended_asin "${p.intended_asin}" is not a valid ASIN shape`);
  if (!asin) {
    rows.push({ product_id: p.id, asin_used: null, candidate_url: null, status: "withheld - link did not resolve", validated: false, destination_confirmed: false, tracking_report_confirmed: false, asin_provenance: "unresolved" });
    continue;
  }
  if (!ASIN.test(asin)) errs.push(`${p.id}: observed ASIN "${asin}" is not 10 characters`);
  const u = new URL(p.official_listing_url);
  if (!/(?:^|\.)amazon\.com$/.test(u.hostname)) errs.push(`${p.id}: official_listing_url host "${u.hostname}" is not amazon.com - only the Schedule 1 marketplace may be linked`);
  if (u.pathname.split("/dp/")[1] && u.pathname.split("/dp/")[1].split("/")[0].toUpperCase() !== asin.toUpperCase()) errs.push(`${p.id}: listing URL and recorded ASIN disagree`);
  rows.push({
    product_id: p.id,
    asin_used: asin,
    asin_provenance: p.intended_asin ? "owner_confirmed" : "observed_redirect",
    candidate_url: `https://www.amazon.com/dp/${asin}?tag=${TRACK}&linkCode=ll1&language=en_US`,
    status: p.intended_asin ? "tagged, identity owner-confirmed" : "candidate - identity from redirect only (FLG-001)",
    validated: false,
    destination_confirmed: false,
    tracking_report_confirmed: false,
    note: p.intended_asin ? null : "No link is marked validated until the one-link test in the register's protocol has been run inside an enrolled Associates workflow."
  });
}

if (csv) {
  const head = "product_id,asin,link_text_to_verify,click_this_to_test,identity_owner_confirmed,destination_confirmed,tracking_report_confirmed,access_date";
  const body = rows.map((r) => [r.product_id, r.asin_used || "", productsDoc.products.find((p) => p.id === r.product_id)?.official_listing_url || "", r.candidate_url || "", r.asin_provenance === "owner_confirmed" ? "yes" : "NO", "no", "no", productsDoc.retrieval.accessed_date].map((c) => `"${String(c).replace(/"/g, '""')}"`).join(","));
  process.stdout.write([head, ...body].join("\n") + "\n");
  process.exit(errs.length ? 1 : 0);
}

if (write) {
  const existing = fs.existsSync(path.join(ROOT, "register/links.json")) ? R("register/links.json") : null;
  const out = {
    $comment: existing?.$comment || "Special Link register, generated by scripts/links.mjs - do not hand-edit link URLs, change register/products.json and re-run.",
    format: existing?.format || { template: "https://www.amazon.com/dp/{ASIN}?tag={TRACKING_ID}&linkCode=ll1&language=en_US", rationale: "Derived, never typed.", rel_attribute: "sponsored nofollow noopener noreferrer", source_id: "S01" },
    tracking_id: TRACK,
    links: rows.map((r) => ({ ...r, ...(existing?.links.find((e) => e.product_id === r.product_id) && r.candidate_url === existing.links.find((e) => e.product_id === r.product_id).candidate_url ? { validated: existing.links.find((e) => e.product_id === r.product_id).validated } : {}) })),
    one_link_test_protocol: existing?.one_link_test_protocol,
    generated_by: "scripts/links.mjs",
    generated_at: new Date().toISOString()
  };
  fs.writeFileSync(path.join(ROOT, "register/links.json"), JSON.stringify(out, null, 2) + "\n");
  console.log(`links: rewrote register/links.json (${rows.length} rows)`);
}

console.log(`links: checked ${rows.length} rows against ${TRACK}`);
if (advisories.length) { console.log(`  ${advisories.length} advisory record(s) - expected while FLG-001 is open:`); advisories.forEach((a) => console.log("   ~ " + a)); }
rows.forEach((r) => console.log(`  ${r.product_id}  ${r.asin_used || "—"}  ${r.status}`));
if (errs.length) { console.log(`\n  ${errs.length} problem(s):`); errs.forEach((e) => console.log("   ! " + e)); process.exit(1); }
console.log("  ok - every published link is derived from a 10-character ASIN and carries the site tag");
